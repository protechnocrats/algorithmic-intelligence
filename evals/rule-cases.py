#!/usr/bin/env python3
"""Builds docs/RULE-EVIDENCE.md: which eval cases test each mandatory rule and each skill file.

    python3 evals/rule-cases.py           rewrite docs/RULE-EVIDENCE.md
    python3 evals/rule-cases.py --check   exit 1 if the file is out of date or a case names a
                                          rule or file that does not exist (CI runs this)

The source of truth is the case table at the top of each answer key in evals/answers/: its
"Rules tested" column. The table is generated, never edited by hand, so it cannot drift from
the cases. Policy (CONTRIBUTING.md, "Pruning rules"): a rule with no case needs a case, not
deletion.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

repo = Path(__file__).resolve().parent.parent
skill = repo / "skills"
out_path = repo / "docs" / "RULE-EVIDENCE.md"
HELD_OUT = {"py-logistics", "rb-clinic"}

rules_text = (skill / "SKILL.md").read_text().split("## Mandatory rules", 1)[1].split("\n## ", 1)[0]
rules = {int(n): t.rstrip(".") for n, t in re.findall(r"^(\d+)\. \*\*(.+?)\*\*", rules_text, re.M)}
skill_files = {p.relative_to(skill).as_posix() for p in skill.rglob("*.md")}

by_rule, by_file, problems, unnamed = defaultdict(list), defaultdict(list), [], []
for key in sorted((repo / "evals" / "answers").glob("*.md")):
    fixture = key.stem
    rows = [l for l in key.read_text().splitlines() if l.startswith("|")]
    if not rows:
        continue
    header = [c.strip() for c in rows[0].strip("|").split("|")]
    col = next((i for i, h in enumerate(header) if h.lower().startswith("rules")), None)
    if col is None:
        problems.append(f"{key.name}: no 'Rules tested' column in the case table")
        continue
    for row in rows[2:]:
        cells = [c.strip() for c in row.strip("|").split("|")]
        if len(cells) <= col or not re.match(r"[A-Z]+W?\d+$", cells[0]):
            continue
        case, cell = f"{fixture} {cells[0]}", cells[col]
        # Rule numbers: "6 (straightforward)", "Rule 10", "rules 4 and 5", "8, 14". Not "500-id" or "2,000".
        nums = re.findall(r"(?:^|[,;]\s*|\b[Rr]ules? |\band |\bor )(\d{1,2})(?![\d,.%-]*\d)(?![-\w])", cell)
        if not nums:
            unnamed.append(case)
        for n in sorted({int(n) for n in nums}):
            if n in rules:
                by_rule[n].append(case)
            else:
                problems.append(f"{key.name} {cells[0]}: rule {n} does not exist")
        for f in sorted(set(re.findall(r"`((?:[\w-]+/)*[\w-]+\.md)`", cell))):
            match = [s for s in skill_files if s == f or s.endswith("/" + f)]
            if match:
                by_file[match[0]].append(case)
            else:
                problems.append(f"{key.name} {cells[0]}: no skill file {f}")


def cases(lst):
    held = [c for c in lst if c.split()[0] in HELD_OUT]
    return ", ".join(lst) + (f" ({len(held)} held out)" if held else "")


lines = [
    "# Rule evidence",
    "",
    "<!-- Generated by evals/rule-cases.py from the answer keys in evals/answers/. Do not edit by hand: change an answer key's \"Rules tested\" column and rerun the script. CI fails when this file is out of date. -->",
    "",
    "Which evaluation cases test each mandatory rule in `skills/SKILL.md`, and each skill file named in an answer key. A case \"tests\" a rule when its answer key says so; whether a run passed is in `evals/results/`.",
    "",
    "**Reading this table:** a rule with no case has not been tested yet. That calls for writing a case, not for deleting the rule. A rule is removed only after a before-and-after run shows the same results without it, and with the maintainer's approval (`CONTRIBUTING.md`, \"Pruning rules\"). Every case also tests rule 3 implicitly, since the probes compare each session's code with the original; only cases that name it are listed.",
    "",
    "| Rule | Cases | Count |",
    "|---|---|---|",
]
for n, title in rules.items():
    lst = by_rule.get(n, [])
    lines.append(f"| {n}. {title} | {cases(lst) if lst else '**none yet**'} | {len(lst)} |")
lines += ["", "## Skill files named by cases", "", "| File | Cases | Count |", "|---|---|---|"]
for f in sorted(by_file):
    lines.append(f"| `{f}` | {cases(by_file[f])} | {len(by_file[f])} |")
lines += ["", "## Cases that name no rule", "", "These test concepts (hidden inputs, cost of existing code from new code, resource bounds) that no single rule owns. Tag one with a rule in its answer key when a rule clearly owns it.", "", ", ".join(unnamed) if unnamed else "None."]
text = "\n".join(lines) + "\n"

for p in problems:
    print("PROBLEM  " + p)
if "--check" in sys.argv:
    stale = not out_path.exists() or out_path.read_text() != text
    if stale:
        print(f"{out_path.relative_to(repo)} is out of date: run python3 evals/rule-cases.py and commit it")
    sys.exit(1 if stale or problems else 0)
out_path.write_text(text)
untested = [n for n in rules if not by_rule.get(n)]
print(f"wrote {out_path.relative_to(repo)}: {len(rules)} rules, untested: {untested or 'none'}")
sys.exit(1 if problems else 0)
